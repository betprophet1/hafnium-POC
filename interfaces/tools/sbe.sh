#!/usr/bin/env bash
# Validate the journal schema with the real SBE tool (warnings are errors), regenerate the committed Rust codec
# crate core/journal, generate the Java codecs into interfaces/generated/java (not committed), stamp core/journal
# with the schema's SHA-256, and run the codec round-trip tests.
#
#   JAVA=/path/to/java SBE_JAR=/path/to/sbe-all-1.40.1.jar interfaces/tools/sbe.sh
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
: "${JAVA:?set JAVA to a JDK 17+ java binary}"
: "${SBE_JAR:?set SBE_JAR to sbe-all-1.40.1.jar}"
SCHEMA_REL="interfaces/sbe/venue-journal.xml"
OUT="$ROOT/interfaces/generated"
JOURNAL="$ROOT/core/journal"

rm -rf "$OUT" && mkdir -p "$OUT"
for lang in Rust Java; do
  "$JAVA" -Dsbe.validation.stop.on.error=true -Dsbe.validation.warnings.fatal=true \
          -Dsbe.target.language="$lang" -Dsbe.output.dir="$OUT/${lang,,}" \
          -jar "$SBE_JAR" "$ROOT/$SCHEMA_REL"
done
echo "valid: $SCHEMA_REL"

# The engine is no_std (blueprint §4). sbe-tool 1.40.1's Rust output uses two std paths with core equivalents;
# rewrite them, mark the crate no_std and unpublished, and fail if any std path remains.
CRATE="$OUT/rust/venue_journal"
sed -i 's/std::iter::repeat/core::iter::repeat/g; s/impl std::error::Error for SbeErr/impl core::error::Error for SbeErr/' "$CRATE"/src/*.rs
sed -i '1i #![no_std]' "$CRATE/src/lib.rs"
sed -i 's/^\[package\]$/[package]\npublish = false/' "$CRATE/Cargo.toml"
if grep -rn 'std::' "$CRATE/src"; then echo "generated Rust still uses std" >&2; exit 1; fi

rm -rf "$JOURNAL/src"
mkdir -p "$JOURNAL"
cp -r "$CRATE/src" "$JOURNAL/src"
cp "$CRATE/Cargo.toml" "$JOURNAL/Cargo.toml"
(cd "$ROOT" && sha256sum "$SCHEMA_REL") > "$JOURNAL/SCHEMA.sha256"
cat > "$JOURNAL/README.md" <<EOF
# venue_journal (generated)

Rust codecs for \`$SCHEMA_REL\`, generated by \`interfaces/tools/sbe.sh\` with sbe-all 1.40.1 and made \`no_std\`.
Do not edit: change the schema and regenerate. \`SCHEMA.sha256\` records the schema this was generated from;
\`./check\` fails when they differ.
EOF
echo "regenerated core/journal"

(cd "$ROOT/core" && cargo test --quiet -p venue-harness --test journal_roundtrip)
